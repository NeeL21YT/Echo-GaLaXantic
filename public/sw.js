// Minimal offline cache: network-first for navigations, cache-first for hashed assets.
// Bump CACHE when the caching strategy changes; hashed asset names handle normal releases.
const CACHE = 'echo-v1';

self.addEventListener('install', (event) => {
  // Also cache the hashed JS/CSS the shell references, so going offline right after the first load works
  // (those files were fetched before this worker controlled the page and would otherwise not be cached).
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      await cache.addAll(['/', '/index.html']);
      const html = await (await cache.match('/index.html')).text();
      const assets = [...html.matchAll(/(?:src|href)="(\/assets\/[^"]+)"/g)].map((m) => m[1]);
      await cache.addAll(assets);
    }),
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put('/index.html', copy));
          return res;
        })
        .catch(() => caches.match('/index.html').then((hit) => hit ?? Response.error())),
    );
    return;
  }

  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ??
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
